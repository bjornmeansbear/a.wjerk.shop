#!/usr/bin/env node
/**
 * works-sync.js — pull the portfolio index out of Notion and write the
 * public slice of it to works.json.
 *
 * Same shape as arena-sync.js: run by hand, never from build.sh. A deploy
 * shouldn't depend on Notion being reachable, or need NOTION_TOKEN in
 * Cloudflare's build environment. Run this after editing rows in Notion,
 * commit works.json, and works.js renders works.html from it at build time.
 *
 * Two databases, both shared with the read-only “wjerk-sync” integration:
 *   Works                   one row per project, 2003 on
 *   People & Organizations  clients, collaborators, studios
 *
 * Only rows with Visibility = Public reach works.json, and only the fields
 * listed in publicRow() — Notes, Old description and the other working
 * fields stay out. A credit is published only when its People row has
 * “OK to name” checked; otherwise the name is dropped, not anonymized.
 *
 * The full snapshot (every row, every field) goes to the private repo when
 * it's cloned alongside, as a backup that git can diff. It never goes here:
 * Notes name clients and private work.
 *
 * Usage: node works-sync.js
 * Reads: .env (NOTION_TOKEN)
 * Writes: works.json, ../a.wjerk.shop-private/works-snapshot.json (if present)
 */

import fs from 'node:fs';
import { NOTION_API, notionToken } from './lib.js';

const WORKS = '4babdc43-0cf3-4915-bfed-2b86c9d4fd27';
const PEOPLE = 'fb80530d-6bab-4550-b20a-025d5838d276';
const PRIVATE_DIR = new URL('../a.wjerk.shop-private/', import.meta.url).pathname;

async function queryAll(dataSource, token) {
  const rows = [];
  let cursor;
  do {
    const res = await fetch(`${NOTION_API}/data_sources/${dataSource}/query`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Notion-Version': '2025-09-03',
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ page_size: 100, ...(cursor && { start_cursor: cursor }) }),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status} from ${dataSource}: ${await res.text()}`);
    const data = await res.json();
    rows.push(...data.results);
    cursor = data.has_more ? data.next_cursor : null;
  } while (cursor);
  return rows;
}

/** One Notion property → a plain value (string, number, array, or null). */
function plain(prop) {
  if (!prop) return null;
  const v = prop[prop.type];
  switch (prop.type) {
    case 'title':
    case 'rich_text':
      return v.map((t) => t.plain_text).join('').trim() || null;
    case 'select':
      return v?.name ?? null;
    case 'multi_select':
      return v.map((o) => o.name);
    case 'relation':
      return v.map((r) => r.id);
    case 'date':
      return v?.start ?? null;
    case 'checkbox':
      return v;
    default: // number, url
      return v ?? null;
  }
}

const flatten = (page) => ({
  id: page.id,
  ...Object.fromEntries(Object.entries(page.properties).map(([k, p]) => [k, plain(p)])),
});

/** “Other links” is one link per line: label | text | url. */
function parseLinks(raw) {
  if (!raw) return [];
  return raw.split('\n').map((line) => line.split('|').map((s) => s.trim()))
    .filter((parts) => parts.length === 3 && /^https?:\/\//.test(parts[2]))
    .map(([label, text, url]) => ({ label, text, url }));
}

function publicRow(w, nameable) {
  const names = (ids) => (ids ?? []).map((id) => nameable.get(id)).filter(Boolean);
  const row = {
    title: w.Title,
    year: w.Year,
    yearEnd: w['Year end'],
    // Completed sorts rows inside a year. Only when it's a real date, not
    // the placeholder 1st-of-the-month a “Month (folder name)” row carries.
    completed: w['Date precision'] === 'Year only' ? null : w.Completed,
    kind: w.Kind,
    oneLiner: w['One-liner'],
    caseStudy: w['Case study'],
    site: w.Site,
    shop: w.Shop,
    repo: w.Repo,
    archive: w.Archive,
    links: parseLinks(w['Other links']),
    tags: w.Categories ?? [],
    for: names(w.For),
    with: names(w.With),
    studio: names(w.Studio),
  };
  // Drop empty fields so works.json stays readable in a diff.
  return Object.fromEntries(Object.entries(row).filter(([, v]) => v != null && !(Array.isArray(v) && !v.length)));
}

async function main() {
  const token = notionToken();
  const [works, people] = await Promise.all([queryAll(WORKS, token), queryAll(PEOPLE, token)]);
  const W = works.map(flatten);
  const P = people.map(flatten);

  const nameable = new Map(P.filter((p) => p['OK to name']).map((p) => [p.id, p.Name]));

  const pub = W.filter((w) => w.Visibility === 'Public');
  // A Public row with no year can't be placed on a chronological page.
  const undated = pub.filter((w) => w.Year == null);
  for (const w of undated) console.warn(`  ⚠ “${w.Title}” is Public but has no Year — left out.`);

  const out = {
    _comment: 'Generated by works-sync.js from Notion. Do not edit by hand; edit the Notion rows and re-run.',
    syncedAt: new Date().toISOString(),
    works: pub.filter((w) => w.Year != null).map((w) => publicRow(w, nameable)),
  };
  fs.writeFileSync('works.json', JSON.stringify(out, null, 2) + '\n');
  console.log(`works.json written: ${out.works.length} public of ${W.length} rows (${nameable.size} credits OK to name).`);

  if (fs.existsSync(PRIVATE_DIR)) {
    const snapshot = { syncedAt: out.syncedAt, works: W, people: P };
    fs.writeFileSync(`${PRIVATE_DIR}works-snapshot.json`, JSON.stringify(snapshot, null, 2) + '\n');
    console.log(`Full snapshot written to ${PRIVATE_DIR}works-snapshot.json`);
  } else {
    console.log('Private repo not cloned alongside — full snapshot skipped.');
  }
}

main().catch((err) => {
  // Leave the last good works.json alone; a half-written one would drop rows from the next deploy.
  console.error(`✗ ${err.message}`);
  process.exitCode = 1;
});
